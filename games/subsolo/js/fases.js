// As nove fases do SUBSOLO, em planta ASCII — um caractere por celula de 1x1.
//
// A planta e o dado canonico: geometria, luz, item e inimigo moram todos aqui, e
// nenhum deles e sorteado em tempo de jogo. Fase que se monta sozinha nao se
// prova; esta se prova em provas.mjs, celula por celula.
//
// A legenda inteira, agrupada:
//
//   parede   # rocha   = concreto   % chapa
//   porta    / livre   1 2 3 travada pelo cracha A B C   * parede falsa
//   piso     . seco    ~ poca (molhado faz ruido)   o lampada acesa
//   saida    E elevador            inicio  @
//   bicho    l larva   r rastejo   c cego   u cuspidor   x capataz
//   item     P pinos   T cartuchos   G gas   V pilha   K kit
//   chave    A B C crachas          arma    S espingarda   M macarico
//
// A escala de cinza de cada fase esta em `paleta`: o raycaster tinge parede,
// piso e teto com ela, entao nove fases nao parecem a mesma fase escura.

